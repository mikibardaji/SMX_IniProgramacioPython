# Dinero que me quedara al llegar a casa
#Inicializo valor que tengo en mi cartera (Inventado)
carteraBanco = 500000
print(f"Al empezar tengo {carteraBanco} euros")
# Me toca la loteria 36000 y ahora enseño cuanto dinero tengo
print("Te ha tocado la loteria que son 36000 euros.")
carteraBanco = carteraBanco + 36000
print(f"En la cartera ahora tienes {carteraBanco} euros" )
# ME atracan y me quitan 15000 euros y enseño cuanto dinero tengo
print(" Me han atracado y me quitan 15000 euros")
carteraBanco = carteraBanco - 15000
print(f"En la cartera ahora tienes {carteraBanco} euros" )
# Al llegar a casa lo reparto entre mis hermanos (son 2) y muestro cuando dinero me queda
print("llego a casa y lo reparto entre yo y mis dos hermanos")
carteraBanco = carteraBanco / 3
print(f"En la cartera ahora tienes {carteraBanco} euros" )
